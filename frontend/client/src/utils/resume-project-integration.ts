/**
 * Hook to automatically trigger CV update on project completion
 * Call this in ProjectTimeline component when a project is marked as completed
 */
export function useProjectCompletionTrigger() {
  const handleProjectCompleted = async (projectData: ProjectCompletionEvent) => {
    try {
      await addCompletedProjectToResumes(projectData);
      
      // Show notification
      if (typeof window !== 'undefined' && 'Notification' in window) {
        if (Notification.permission === 'granted') {
          new Notification('CV oppdatert! 🎉', {
            body: `Prosjektet "${projectData.projectTitle}" er lagt til i CV-en din`,
            icon: '/logo.png',
          });
        }
      }
    } catch (error) {
      console.error('Failed to auto-update CV:', error);
    }
  };

  return { handleProjectCompleted };
}

/**
 * Check if a project already exists in a resume
 */
export async function isProjectInResume(
  resumeId: string,
  projectId: string,
  userId: string
): Promise<boolean> {
  try {
    const resume = await apiRequest(`/api/resumes/${resumeId}`, {
      headers: {'x-user-id': userId },
    });

    const existsInExperience = resume.experiences?.some(
      (exp: any) => exp.projectId === projectId
    );
    
    const existsInProjects = resume.projects?.some(
      (proj: any) => proj.projectId === projectId
    );

    return existsInExperience || existsInProjects;
  } catch (error) {
    console.error('Failed to check project in resume:', error);
    return false;
  }
}

