/**
 * CreatorHub Norge - Resume & Project Timeline Integration
 * Automatically updates CV when projects are completed
 */

import { apiRequest } from '@/lib/queryClient';

export interface ProjectCompletionEvent {
  projectId: string;
  projectTitle: string;
  clientName: string;
  projectType: string;
  description?: string;
  location?: string;
  startDate?: string;
  endDate: string;
  completedAt: string;
  userId: string;
}

/**
 * Automatically add completed project to all active resumes
 */
export async function addCompletedProjectToResumes(
  projectData: ProjectCompletionEvent
): Promise<void> {
  try {
    // Get all active resumes for the user
    const resumes = await apiRequest('/api/resumes', {
      headers: { 'x-user-id': projectData.userId },
    });

    if (!resumes || resumes.length === 0) {
      console.log('No active resumes found, skipping auto-add to CV');
      return;
    }

    // Add to each active resume
    for (const resume of resumes) {
      if (resume.status === 'active' || resume.status === 'draft') {
        await addProjectExperience(resume.id, projectData);
        await addPortfolioProject(resume.id, projectData);
      }
    }

    console.log(`✅ Project ${projectData.projectTitle} added to ${resumes.length} resume(s)`);
  } catch (error) {
    console.error('Failed to add project to resumes: ', error);
    throw error;
  }
}

/**
 * Add project as work experience
 */
async function addProjectExperience(
  resumeId: string,
  projectData: ProjectCompletionEvent
): Promise<void> {
  try {
    await apiRequest(`/api/resumes/${resumeId}/experiences`, {
      method: 'POST',
      headers: {
        'x-user-id': projectData.userId,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        jobTitle: getJobTitleFromProjectType(projectData.projectType),
        company: projectData.clientName,
        location: projectData.location || ', ',
        employmentType: 'freelance',
        startDate: projectData.startDate || projectData.completedAt,
        endDate: projectData.endDate,
        isCurrent: false,
        description: projectData.description || `Successful ${projectData.projectType} project for ${projectData.clientName}`,
        achievements: [],
        skills: extractSkillsFromProjectType(projectData.projectType),
        projectId: projectData.projectId,
        autoGenerated: true,
        isVisible: true,
      }),
    });
  } catch (error) {
    console.error('Failed to add project experience:', error);
  }
}

/**
 * Add project to portfolio
 */
async function addPortfolioProject(
  resumeId: string,
  projectData: ProjectCompletionEvent
): Promise<void> {
  try {
    await apiRequest(`/api/resumes/${resumeId}/projects`, {
      method: 'POST',
      headers: {
        'x-user-id': projectData.userId,
        'Content-Type' : 'application/json',
      },
      body: JSON.stringify({
        title: projectData.projectTitle,
        description: projectData.description || `${projectData.projectType} project for ${projectData.clientName}`,
        role: 'Lead',
        startDate: projectData.startDate || projectData.completedAt,
        endDate: projectData.endDate,
        technologies: extractTechnologiesFromProjectType(projectData.projectType),
        achievements: [],
        projectUrl: ', ',
        images: [],
        projectId: projectData.projectId,
        autoGenerated: true,
        isVisible: true,
      }),
    });
  } catch (error) {
    console.error('Failed to add portfolio project:', error);
  }
}

/**
 * Get appropriate job title based on project type
 */
function getJobTitleFromProjectType(projectType: string): string {
  const titleMap: Record<string, string> = {
    'wedding':'Bryllupsfotograf','portrait':'Portrettfotograf','event':'Event-fotograf','commercial':'Kommersiell fotograf','video':'Videograf','music':'Musikkprodusent','family':'Familie-fotograf','product' : 'Produktfotograf',
  };

  return titleMap[projectType] || 'Kreativ profesjonell';
}

