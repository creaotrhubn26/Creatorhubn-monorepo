export type PropCategory = 
  | 'furniture' 
  | 'electronics' 
  | 'decorations' 
  | 'tools' 
  | 'vehicles' 
  | 'nature' 
  | 'architecture'
  | 'lighting'
  | 'other';

export type PropStyle = 
  | 'modern' 
  | 'vintage' 
  | 'industrial' 
  | 'minimalist' 
  | 'rustic' 
  | 'contemporary'
  | 'traditional';

export type PropSize = 'small' | 'medium' | 'large' | 'extra-large';

export type PropComplexity = 'low' | 'medium' | 'high' | 'very-high';

// ============================================================================
// Prop Definition Interface
// ============================================================================

export interface PropDefinition {
  id: string;
  name: string;
  description: string;
  category: PropCategory;
  style?: PropStyle;
  size: PropSize;
  complexity: PropComplexity;
  modelPath: string;
  meshName?: string; // For multi-mesh GLB files
  thumbnailPath?: string;
  polyCount?: number;
  tags?: string[];
  
  // Physical properties
  dimensions?: {
    width: number;  // meters
    height: number; // meters
    depth: number;  // meters
  };
  
  // Optimization hints
  supportsLOD?: boolean; // Whether LOD is beneficial
  supportsInstancing?: boolean; // Whether GPU instancing is beneficial
  recommendedMaxInstances?: number; // Recommended max instances
}

