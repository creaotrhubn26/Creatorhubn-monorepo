export type AutoMonitorConfig = typeof autoMonitorConfigs.$inferSelect;
export type ProcessedFile = typeof processedFiles.$inferSelect;
export type ContentAnalysisCache = typeof contentAnalysisCache.$inferSelect;
export type StoryArcTemplate = typeof storyArcTemplates.$inferSelect;

// Insert types
export type InsertStoryArcProject = z.infer<typeof insertStoryArcProjectSchema>;
export type InsertAutoMonitorConfig = z.infer<typeof insertAutoMonitorConfigSchema>;
export type InsertProcessedFile = z.infer<typeof insertProcessedFileSchema>;
export type InsertContentAnalysisCache = z.infer<typeof insertContentAnalysisCacheSchema>;
export type InsertStoryArcTemplate = z.infer<typeof insertStoryArcTemplateSchema>;

// API schemas for validation
