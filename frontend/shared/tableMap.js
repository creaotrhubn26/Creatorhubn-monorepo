const tableNameMap = Object.fromEntries(camelTables.map((name) => [name, toSnakeCase(name)]));

// Helper to get DB table name from camel key
function dbName(camel) {
  return tableNameMap[camel] ?? toSnakeCase(camel);
}

// When run directly: print and write JSON
if (import.meta.url === `file://${process.argv[1]}`) {
  console.log(tableNameMap);
  try {
    const fs = await import('node:fs/promises');
    await fs.writeFile('./tools/tableMap.json', JSON.stringify(tableNameMap, null, 2));
    console.log('→ Wrote ./tools/tableMap.json');
  } catch (e) {
    console.warn('Could not write tableMap.json:', e.message);
  }
}

