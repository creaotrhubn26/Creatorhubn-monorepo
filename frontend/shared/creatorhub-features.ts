// Helper functions for feature management
export const getFeaturesByProfession = (
  profession: 'photographer' | 'videographer' | 'musicproducer' | 'admin' | 'vendor',
): CreatorHubFeature[] => {
  return CREATORHUB_FEATURES.filter((feature) => feature.professions.includes(profession));
};

export const getFeaturesByPlan = (plan: 'basic' | 'pro' | 'enterprise'): CreatorHubFeature[] => {
  const planHierarchy = { basic: 0, pro: 1, enterprise: 2 };
  const targetLevel = planHierarchy[plan];

  return CREATORHUB_FEATURES.filter((feature) => {
    const featureLevel = planHierarchy[feature.requiredPlan];
    return featureLevel <= targetLevel;
  });
};

export const getCoreFeatures = (): CreatorHubFeature[] => {
  return CREATORHUB_FEATURES.filter((feature) => feature.isCore);
};

export const getFeaturesByCategory = (category: string): CreatorHubFeature[] => {
  return CREATORHUB_FEATURES.filter((feature) => feature.category === category);
};

export const getFeatureById = (id: string): CreatorHubFeature | undefined => {
  return CREATORHUB_FEATURES.find((feature) => feature.id === id);
};

