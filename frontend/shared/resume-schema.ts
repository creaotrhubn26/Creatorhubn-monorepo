/**
 * AI Analysis Results
 * Store AI-generated suggestions and improvements
 */
export const resumeAiAnalyses = pgTable(
  'resume_ai_analyses',
  {
    id: varchar('id')
      .primaryKey()
      .$defaultFn(() => crypto.randomUUID()),
    resumeId: varchar('resume_id')
      .notNull()
      .references(() => resumes.id),
    userId: varchar('user_id').notNull(),

    // Analysis Type
    analysisType: varchar('analysis_type', { length: 50 })
      .$type<'ats_optimization' | 'keyword_match' | 'content_improvement' | 'grammar_check'>()
      .notNull(),

    // Results
    score: integer('score'), // 0-100
    suggestions: jsonb('suggestions').$type<
      Array<{
        type: string;
        severity: 'low' | 'medium' | 'high';
        message: string;
        suggestion: string;
      }>
    >(),

    // Keywords Analysis
    matchedKeywords: text('matched_keywords').array(),
    missingKeywords: text('missing_keywords').array(),

    // Job Description Match
    jobDescription: text('job_description'),
    matchScore: integer('match_score'), // 0-100

    analyzedAt: timestamp('analyzed_at').defaultNow().notNull(),
  },
  (table) => ({
    resumeIdIdx: index('resume_ai_analyses_resume_id_idx').on(table.resumeId),
    analysisTypeIdx: index('resume_ai_analyses_type_idx').on(table.analysisType),
  }),
);

