/**
 * Job Application Tracking
 * Track job applications with Norwegian job sites
 */
export const jobApplications = pgTable(
  'job_applications',
  {
    id: varchar('id')
      .primaryKey()
      .$defaultFn(() => crypto.randomUUID()),
    userId: varchar('user_id').notNull(),
    resumeId: varchar('resume_id').references(() => resumes.id),

    // Job Details
    jobTitle: varchar('job_title', { length: 255 }).notNull(),
    company: varchar('company', { length: 255 }).notNull(),
    location: varchar('location', { length: 255 }),
    jobUrl: varchar('job_url', { length: 500 }),

    // Source
    source: varchar('source', { length: 100 }), // 'finn.no', 'nav.no', 'linkedin', etc.
    jobId: varchar('job_id', { length: 255 }), // External job ID

    // Application Status
    status: varchar('status', { length: 50 })
      .$type<
        'saved' | 'applied' | 'interviewing' | 'offer' | 'rejected' | 'accepted' | 'withdrawn'
      >()
      .default('saved'),

    appliedDate: timestamp('applied_date'),
    responseDate: timestamp('response_date'),
    interviewDate: timestamp('interview_date'),
    offerDate: timestamp('offer_date'),

    // Application Details
    coverLetter: text('cover_letter'),
    notes: text('notes'),
    salary: varchar('salary', { length: 100 }),

    // Reminders & Follow-ups
    followUpDate: timestamp('follow_up_date'),
    reminderSent: boolean('reminder_sent').default(false),

    // Metadata
    priority: varchar('priority', { length: 20 })
      .$type<'low' | 'medium' | 'high'>()
      .default('medium'),
    tags: text('tags').array(),

    createdAt: timestamp('created_at').defaultNow().notNull(),
    updatedAt: timestamp('updated_at').defaultNow().notNull(),
  },
  (table) => ({
    userIdIdx: index('job_applications_user_id_idx').on(table.userId),
    statusIdx: index('job_applications_status_idx').on(table.status),
    sourceIdx: index('job_applications_source_idx').on(table.source),
  }),
);

