#!/usr/bin/env node
/**
 * TikTok App Review screencast: video.upload (Content Posting API).
 *
 * Records a single video showing The Role Room's TikTok integration
 * end-to-end:
 *
 *   1. Title card naming the scope + use case
 *   2. The Role Room agent dialog → Feed Planner → TikTok tab
 *   3. TikTokConnectionCard → click "Koble TikTok"
 *   4. Operator goes through TikTok OAuth in popup (manual)
 *   5. Returns to The Role Room → connected state with avatar + handle
 *   6. (optional) Click publish on a feed-plan post → backend uploads to
 *      TikTok creator inbox via /v2/post/publish/inbox/video/init/
 *   7. Closing card describing the use case
 *
 * Usage (interactive — prompts before recording):
 *   node backend/scripts/record-tiktok-app-review-demo.playwright.mjs
 *
 * Required env (read from .env.tiktok.demo.local if present, else
 * prompted at start):
 *   - APP_BASE_URL  (e.g. https://creatorhub-backend-rtbl.onrender.com)
 *   - DEMO_PROJECT_ID  (a project where TikTok feed-plan exists)
 *
 * USE_USER_CHROME=1: bruk din installerte Chrome (med daniel@creatorhubn.com
 * allerede innlogget). Krever at Chrome er HELT lukket (cmd+Q) før kjøring.
 *
 * Output:
 *   recordings/tiktok-app-review-{timestamp}.webm
 *   (auto-konverteres til .mp4 hvis ffmpeg er installert)
 */

import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import readline from 'node:readline/promises';
import { spawn } from 'node:child_process';
import { stdin as input, stdout as output } from 'node:process';

// ── Config ────────────────────────────────────────────────────────────────

const REPO_ROOT = path.resolve(process.cwd());
const VIDEO_DIR = path.resolve(REPO_ROOT, 'recordings');
const ROLE_ROOM_STATE = path.resolve(REPO_ROOT, '.role-room-admin-state.json');
const ENV_FILE = path.resolve(REPO_ROOT, 'backend/.env.tiktok.demo.local');

const DEFAULT_APP_BASE = 'https://creatorhub-backend-rtbl.onrender.com';
const HEADLESS = process.env.HEADLESS === '1';
const VIEWPORT = { width: 1440, height: 900 };

const USE_USER_CHROME = process.env.USE_USER_CHROME === '1';
const USER_CHROME_PROFILE =
  process.env.CHROME_PROFILE_PATH ||
  `${process.env.HOME}/Library/Application Support/Google/Chrome`;
const USER_CHROME_PROFILE_DIR = process.env.CHROME_PROFILE_DIR || 'Default';

// ── Utilities ─────────────────────────────────────────────────────────────

const rl = readline.createInterface({ input, output });
const ask = (q) => rl.question(q);

function log(msg) {
  console.log(`[${new Date().toISOString().split('T')[1].slice(0, 8)}] ${msg}`);
}

async function ensureDir(dir) {
  await fs.mkdir(dir, { recursive: true });
}

async function loadEnv() {
  const out = {
    APP_BASE_URL: process.env.APP_BASE_URL || DEFAULT_APP_BASE,
    DEMO_PROJECT_ID: process.env.DEMO_PROJECT_ID || '',
  };
  try {
    const raw = await fs.readFile(ENV_FILE, 'utf8');
    for (const line of raw.split('\n')) {
      const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
      if (!m) continue;
      const [, k, v] = m;
      if (out[k] !== undefined && !out[k]) {
        out[k] = v.replace(/^['"]|['"]$/g, '').trim();
      }
    }
  } catch {}
  return out;
}

async function saveEnv(env) {
  const lines = [
    '# Auto-generated by record-tiktok-app-review-demo.playwright.mjs',
    '# Reused for subsequent runs. NOT for git.',
    `APP_BASE_URL=${env.APP_BASE_URL}`,
    `DEMO_PROJECT_ID=${env.DEMO_PROJECT_ID}`,
  ];
  await fs.writeFile(ENV_FILE, lines.join('\n') + '\n', { mode: 0o600 });
}

async function loadState(filepath) {
  try {
    await fs.access(filepath);
    return filepath;
  } catch {
    return undefined;
  }
}

async function openBrowser(opts) {
  if (USE_USER_CHROME) {
    log(`Using existing Chrome profile: ${USER_CHROME_PROFILE} (profile-directory=${USER_CHROME_PROFILE_DIR})`);
    log('NOTE: Chrome must be FULLY quit (cmd+Q) before running, or this will fail with "profile locked".');
    const context = await chromium.launchPersistentContext(USER_CHROME_PROFILE, {
      headless: HEADLESS,
      channel: 'chrome',
      args: [
        '--no-sandbox',
        `--profile-directory=${USER_CHROME_PROFILE_DIR}`,
        '--disable-blink-features=AutomationControlled',
      ],
      locale: 'en-US',
      viewport: VIEWPORT,
      recordVideo: { dir: VIDEO_DIR, size: VIEWPORT },
    });
    return { context, browser: null, ownsBrowser: false };
  }
  const browser = await chromium.launch({ headless: HEADLESS, args: ['--no-sandbox'] });
  const context = await browser.newContext({
    storageState: await loadState(opts.storageStatePath),
    locale: 'en-US',
    viewport: VIEWPORT,
    recordVideo: { dir: VIDEO_DIR, size: VIEWPORT },
  });
  return { context, browser, ownsBrowser: true };
}

async function closeBrowserBundle(bundle) {
  await bundle.context.close().catch(() => {});
  if (bundle.ownsBrowser && bundle.browser) {
    await bundle.browser.close().catch(() => {});
  }
}

async function beat(page, ms = 1500) {
  await page.waitForTimeout(ms);
}

