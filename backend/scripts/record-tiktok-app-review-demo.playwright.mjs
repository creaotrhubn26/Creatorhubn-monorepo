async function showTitleCard(page, h1, h2, body, durationMs = 7000) {
  await page.evaluate(({ h1, h2, body }) => {
    const existing = document.getElementById('ar-title');
    if (existing) existing.remove();
    const el = document.createElement('div');
    el.id = 'ar-title';
    el.innerHTML = `<h2>${h2}</h2><h1>${h1}</h1><p>${body}</p>`;
    document.body.appendChild(el);
    requestAnimationFrame(() => el.classList.add('show'));
  }, { h1, h2, body });
  await beat(page, durationMs);
  await page.evaluate(() => {
    const el = document.getElementById('ar-title');
    if (!el) return;
    el.classList.remove('show');
    setTimeout(() => el.remove(), 600);
  });
  await beat(page, 600);
}

async function showCaption(page, step, text) {
  await page.evaluate(({ step, text }) => {
    const cap = document.getElementById('ar-caption');
    if (!cap) return;
    cap.innerHTML = `<span class="step">${step}</span>${text}`;
    cap.classList.add('show');
  }, { step, text });
}

async function hideCaption(page) {
  await page.evaluate(() => {
    const cap = document.getElementById('ar-caption');
    if (!cap) return;
    cap.classList.remove('show');
  });
}

async function spotlight(page, locator) {
  try {
    await locator.evaluate((el) => el.classList.add('ar-spot'));
  } catch {}
}

async function unspotlight(page) {
  try {
    await page.evaluate(() => {
      document.querySelectorAll('.ar-spot').forEach((el) => el.classList.remove('ar-spot'));
    });
  } catch {}
}

// ── ffmpeg conversion ────────────────────────────────────────────────────

async function convertWebmToMp4(webmPath) {
  const mp4Path = webmPath.replace(/\.webm$/, '.mp4');
  return new Promise((resolve) => {
    const proc = spawn('ffmpeg', [
      '-y',
      '-i', webmPath,
      '-c:v', 'libx264',
      '-preset', 'medium',
      '-crf', '20',
      '-pix_fmt', 'yuv420p',
      '-movflags', '+faststart',
      mp4Path,
    ]);
    let stderr = '';
    proc.stderr.on('data', (d) => { stderr += d.toString(); });
    proc.on('error', (err) => {
      log(`ffmpeg not available (${err.message}) — skipping mp4 conversion`);
      resolve(null);
    });
    proc.on('close', (code) => {
      if (code === 0) {
        log(`✓ Converted to ${path.basename(mp4Path)}`);
        resolve(mp4Path);
      } else {
        log(`ffmpeg failed (code ${code}): ${stderr.split('\n').slice(-3).join(' ')}`);
        resolve(null);
      }
    });
  });
}

// ── Recording flow ────────────────────────────────────────────────────────

async function recordTikTokDemo(env) {
  const bundle = await openBrowser({ storageStatePath: ROLE_ROOM_STATE });
  const { context } = bundle;
  const page = context.pages()[0] ?? (await context.newPage());

  page.on('console', (msg) => {
    if (msg.type() === 'error') {
      const t = msg.text();
      if (!t.includes('favicon') && !t.includes('hydration')) {
        log(`[console.error] ${t.slice(0, 200)}`);
      }
    }
  });

  let videoPath = null;
  try {
    // Step 0: Open The Role Room admin (login if needed)
    const adminUrl = `${env.APP_BASE_URL}/admin`;
    log(`Opening The Role Room: ${adminUrl}`);
    await page.goto(adminUrl, { waitUntil: 'domcontentloaded' });

    // Wait for operator to log in if necessary
    if (!page.url().includes('/admin') || page.url().includes('login')) {
      log('Operator must log in. Pausing up to 5 min.');
      const deadline = Date.now() + 5 * 60 * 1000;
      while (Date.now() < deadline) {
        await page.waitForTimeout(2000);
        if (page.url().includes('/admin') && !page.url().includes('login')) break;
      }
      await context.storageState({ path: ROLE_ROOM_STATE }).catch(() => {});
    }

    await beat(page, 2000);
    await installStyles(page);

    // ── Title card ────────────────────────────────────────────────
    await showTitleCard(
      page,
      'TikTok Content Posting API',
      'The Role Room — TikTok App Review Demo',
      'This screencast demonstrates The Role Room\'s use of the video.upload scope. The Role Room is a SaaS production platform where content producers manage social publishing for their clients. Producers connect their TikTok creator account via OAuth, then use The Role Room to upload videos directly to the creator\'s TikTok inbox. The creator then opens the TikTok app to finalize and publish.',
      9500,
    );

    // ── Step 1: Open Feed Planner / TikTok tab ───────────────────
    await showCaption(
      page,
      'Step 1 of 5',
      'The producer opens The Role Room agent dialog and navigates to the TikTok tab in Feed Planner.',
    );
    await beat(page, 3500);

    // Navigate to the role room agent — depends on app routing.
    // We use the project-specific feed planner URL pattern.
    if (env.DEMO_PROJECT_ID) {
      const feedPlannerUrl = `${env.APP_BASE_URL}/admin/role-room/agent/${encodeURIComponent(env.DEMO_PROJECT_ID)}?platform=tiktok`;
      log(`Navigating to Feed Planner (TikTok tab): ${feedPlannerUrl}`);
      await page.goto(feedPlannerUrl, { waitUntil: 'domcontentloaded' }).catch(() => {});
      await beat(page, 2500);
    } else {
      log('No DEMO_PROJECT_ID configured — operator should navigate manually. Pausing 30s.');
      await beat(page, 30_000);
    }

    // Wait for TikTok connection card to appear
    const tiktokCard = page.locator('[data-testid="tiktok-connection-card"]');
    try {
      await tiktokCard.waitFor({ state: 'visible', timeout: 20_000 });
    } catch {
      log('TikTok card not found — operator may need to switch to TikTok tab manually.');
      await beat(page, 15_000);
    }

    await installStyles(page).catch(() => {});

    await hideCaption(page);
    await beat(page, 500);

    // ── Step 2: Click "Koble TikTok" ──────────────────────────────
    await showCaption(
      page,
      'Step 2 of 5',
      'Producer clicks "Koble TikTok" to start the OAuth flow. The Role Room redirects to TikTok\'s authorization page.',
    );
    await beat(page, 3500);

    const connectButton = page.getByRole('button', { name: /Koble TikTok/i });
    if (await connectButton.count() > 0) {
      await spotlight(page, connectButton.first());
      await beat(page, 2000);
      // Click and wait for popup
      const popupPromise = page.waitForEvent('popup', { timeout: 30_000 }).catch(() => null);
      await connectButton.first().click();
      const popup = await popupPromise;
      await unspotlight(page);
      if (popup) {
        log('OAuth popup opened. Operator must complete TikTok login + authorize. Waiting up to 5 min for popup to close.');
        await hideCaption(page);
        await beat(page, 1500);
        await showCaption(
          page,
          'Step 3 of 5',
          'Producer authenticates with TikTok and grants user.info.basic + video.upload scopes. TikTok redirects back, popup closes, The Role Room receives a connection confirmation via postMessage.',
        );
        // Wait for popup to close (operator finishes OAuth flow)
        try {
          await popup.waitForEvent('close', { timeout: 5 * 60 * 1000 });
          log('OAuth popup closed.');
        } catch {
          log('OAuth popup timeout — continuing anyway.');
        }
      } else {
        log('No popup detected — operator may need to check popup-blocker.');
      }
    } else {
      log('Connect button not found. Maybe already connected — continuing.');
    }

    await beat(page, 4000);
    await hideCaption(page);
    await beat(page, 500);

    // ── Step 4: Show connected state ─────────────────────────────
    await showCaption(
      page,
      'Step 4 of 5',
      'The Role Room shows the connected TikTok account: avatar, display name, and TikTok handle. The encrypted access + refresh tokens are stored in role_room_tiktok_connections.',
    );
    await beat(page, 5000);

    const connectedChip = page.locator('[data-testid="tiktok-connection-card"] .MuiChip-label', {
      hasText: /Koblet/i,
    });
    if (await connectedChip.count() > 0) {
      await spotlight(page, connectedChip.first());
      await beat(page, 4000);
      await unspotlight(page);
    }

    await hideCaption(page);
    await beat(page, 500);

    // ── Step 5: Closing — describe the publish flow ──────────────
    await showCaption(
      page,
      'Step 5 of 5',
      'Producers create posts in Feed Planner. On publish, The Role Room uploads video bytes to TikTok\'s Content Posting API at /v2/post/publish/inbox/video/init/. The video lands in the creator\'s TikTok inbox where they finalize captions, hashtags, and privacy before publishing.',
    );
    await beat(page, 9000);

    await hideCaption(page);
    await beat(page, 600);

    // ── Closing card ─────────────────────────────────────────────
    await showTitleCard(
      page,
      'video.upload — Use Case Summary',
      'The Role Room — SaaS Production Platform',
      'The Role Room helps content producers manage social publishing for their clients across Instagram, Facebook Pages, LinkedIn, YouTube, and TikTok. Producers connect their TikTok creator account once via OAuth, plan content collaboratively with clients, and publish to TikTok\'s inbox via the Content Posting API. The video.upload scope is used solely to upload draft videos for the connected creator to finalize and publish from the TikTok app.',
      11_000,
    );

    log('TikTok demo recording complete — closing context to flush video.');
  } catch (err) {
    log(`Recording error: ${err.message}`);
    try {
      await page.screenshot({
        path: path.join(VIDEO_DIR, `tiktok-fail-${Date.now()}.png`),
        fullPage: true,
      });
    } catch {}
    if (!HEADLESS) await page.waitForTimeout(20_000);
  } finally {
    try {
      videoPath = await page.video()?.path();
    } catch {}
    await closeBrowserBundle(bundle);
  }

  if (videoPath) {
    const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
    const renamed = path.join(VIDEO_DIR, `tiktok-app-review-${stamp}.webm`);
    try {
      await fs.rename(videoPath, renamed);
      log(`✓ Video saved: ${renamed}`);
      const mp4 = await convertWebmToMp4(renamed);
      if (mp4) log(`✓ MP4 ready: ${mp4}`);
    } catch (err) {
      log(`Could not rename video: ${err.message}`);
    }
  }
}

// ── Main ─────────────────────────────────────────────────────────────────

async function main() {
  await ensureDir(VIDEO_DIR);
  let env = await loadEnv();

  if (!env.APP_BASE_URL) {
    env.APP_BASE_URL = (await ask(`APP_BASE_URL [${DEFAULT_APP_BASE}]: `)).trim() || DEFAULT_APP_BASE;
  }
  if (!env.DEMO_PROJECT_ID) {
    env.DEMO_PROJECT_ID = (await ask('DEMO_PROJECT_ID (project where TikTok feed-plan exists): ')).trim();
  }
  await saveEnv(env);

  log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  log('  TikTok App Review Demo Recording');
  log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  log(`  APP_BASE_URL:    ${env.APP_BASE_URL}`);
  log(`  DEMO_PROJECT_ID: ${env.DEMO_PROJECT_ID || '(none — will pause for manual nav)'}`);
  log(`  Output dir:      ${VIDEO_DIR}`);
  log(`  Mode:            ${USE_USER_CHROME ? 'system Chrome' : 'bundled Chromium'}`);
  log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');

  await ask('Press Enter to start recording (Ctrl+C to abort)…');
  await recordTikTokDemo(env);

  rl.close();
  log('Done.');
}

main().catch((err) => {
  console.error('FATAL:', err);
  rl.close();
  process.exit(1);
});
