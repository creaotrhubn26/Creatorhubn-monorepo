#!/usr/bin/env node
/**
 * Meta App Review screencasts: WhatsApp Tech Provider permissions.
 *
 * Records two separate video files — one per permission Meta wants
 * documentation for:
 *
 *   1. whatsapp_business_messaging:
 *      - Title card naming the permission + use case
 *      - The Role Room admin demo page sends a WhatsApp template to
 *        a recipient via Meta Cloud API
 *      - Tab switches to web.whatsapp.com showing the message arriving
 *      - Closing card
 *
 *   2. whatsapp_business_management:
 *      - Title card naming the permission + use case
 *      - business.facebook.com WhatsApp Manager → Templates
 *      - Click "Create Template" → fill in audition_reminder_24h_no
 *      - Submit + verify "In Review" status
 *      - Closing card
 *
 * Usage (interactive — prompts before each video):
 *   node backend/scripts/record-whatsapp-app-review-demo.playwright.mjs
 *
 * Required env (read from .env.whatsapp.demo.local if present, else
 * prompted at start):
 *   - APP_BASE_URL (default: https://creatorhub-backend-rtbl.onrender.com)
 *   - META_APP_ACCESS_TOKEN
 *   - WHATSAPP_PHONE_NUMBER_ID (Meta sandbox phone number ID)
 *   - DEMO_RECIPIENT_PHONE_E164 (your own phone, verified in Meta sandbox)
 *
 * Operator flow on first run:
 *   1. Script opens The Role Room — operator logs in as admin once.
 *   2. State saved to .role-room-admin-state.json — reused next runs.
 *   3. Script opens web.whatsapp.com — operator scans QR once.
 *   4. State saved to .whatsapp-web-state.json — reused next runs.
 *   5. Script opens business.facebook.com — operator already logged in
 *      via Meta SSO from earlier sessions; if not, login manually.
 *   6. State saved to .meta-business-state.json — reused next runs.
 */

import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import readline from 'node:readline/promises';
import { stdin as input, stdout as output } from 'node:process';

// ── Config ────────────────────────────────────────────────────────────────

const REPO_ROOT = path.resolve(process.cwd());
const VIDEO_DIR = path.resolve(REPO_ROOT, 'recordings');
const ROLE_ROOM_STATE = path.resolve(REPO_ROOT, '.role-room-admin-state.json');
const WHATSAPP_WEB_STATE = path.resolve(REPO_ROOT, '.whatsapp-web-state.json');
const META_BUSINESS_STATE = path.resolve(REPO_ROOT, '.meta-business-state.json');
const ENV_FILE = path.resolve(REPO_ROOT, 'backend/.env.whatsapp.demo.local');

const DEFAULT_APP_BASE = 'https://creatorhub-backend-rtbl.onrender.com';
const HEADLESS = process.env.HEADLESS === '1';
const VIEWPORT = { width: 1440, height: 900 };

// ── Utilities ─────────────────────────────────────────────────────────────

const rl = readline.createInterface({ input, output });
const ask = (q) => rl.question(q);

function log(msg) {
  console.log(`[${new Date().toISOString().split('T')[1].slice(0, 8)}] ${msg}`);
}

async function ensureDir(dir) {
  await fs.mkdir(dir, { recursive: true });
}

async function loadEnv() {
  const out = {
    APP_BASE_URL: process.env.APP_BASE_URL || DEFAULT_APP_BASE,
    META_APP_ACCESS_TOKEN: process.env.META_APP_ACCESS_TOKEN || '',
    WHATSAPP_PHONE_NUMBER_ID: process.env.WHATSAPP_PHONE_NUMBER_ID || '',
    WHATSAPP_BUSINESS_ACCOUNT_ID: process.env.WHATSAPP_BUSINESS_ACCOUNT_ID || '',
    DEMO_RECIPIENT_PHONE_E164: process.env.DEMO_RECIPIENT_PHONE_E164 || '',
  };
  try {
    const raw = await fs.readFile(ENV_FILE, 'utf8');
    for (const line of raw.split('\n')) {
      const m = line.match(/^([A-Z_]+)=(.*)$/);
      if (!m) continue;
      const [, k, v] = m;
      if (out[k] !== undefined && !out[k]) out[k] = v.replace(/^['"]|['"]$/g, '').trim();
    }
  } catch {}
  return out;
}

async function saveEnv(env) {
  const lines = [
    '# Auto-generated by record-whatsapp-app-review-demo.playwright.mjs',
    '# Reused for subsequent runs. NOT for git.',
    `APP_BASE_URL=${env.APP_BASE_URL}`,
    `META_APP_ACCESS_TOKEN=${env.META_APP_ACCESS_TOKEN}`,
    `WHATSAPP_PHONE_NUMBER_ID=${env.WHATSAPP_PHONE_NUMBER_ID}`,
    `WHATSAPP_BUSINESS_ACCOUNT_ID=${env.WHATSAPP_BUSINESS_ACCOUNT_ID}`,
    `DEMO_RECIPIENT_PHONE_E164=${env.DEMO_RECIPIENT_PHONE_E164}`,
  ];
  await fs.writeFile(ENV_FILE, lines.join('\n') + '\n', { mode: 0o600 });
}

async function loadState(filepath) {
  try {
    await fs.access(filepath);
    return filepath;
  } catch {
    return undefined;
  }
}

async function beat(page, ms = 1500) {
  await page.waitForTimeout(ms);
}

