#!/usr/bin/env node
// Build a mechanical project baseline (YAML to stdout) for repo-intelligence.
// Usage: node build-baseline.mjs [rootDir]
// Collects: package.json deps (+ resolved versions from nearest package-lock),
// Cargo.toml, pyproject.toml, requirements.txt. No dependencies.

import { readFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, relative, dirname } from "node:path";

const ROOT = process.argv[2] ? process.argv[2] : process.cwd();
const SKIP = new Set(["node_modules", ".git", "target", "dist", "build", ".claude", "DerivedData", "Pods", ".next", "vendor"]);

const manifests = [];
(function walk(dir, depth) {
  if (depth > 6) return;
  let entries;
  try { entries = readdirSync(dir); } catch { return; }
  for (const e of entries) {
    if (SKIP.has(e) || e.startsWith(".")) continue;
    const p = join(dir, e);
    let st;
    try { st = statSync(p); } catch { continue; }
    if (st.isDirectory()) walk(p, depth + 1);
    else if (["package.json", "Cargo.toml", "pyproject.toml", "requirements.txt"].includes(e)) manifests.push(p);
  }
})(ROOT, 0);

// nearest package-lock resolved versions, keyed by lock dir
const lockCache = new Map();
function resolvedVersion(manifestPath, dep) {
  let dir = dirname(manifestPath);
  while (dir.startsWith(ROOT)) {
    const lock = join(dir, "package-lock.json");
    if (existsSync(lock)) {
      if (!lockCache.has(lock)) {
        try { lockCache.set(lock, JSON.parse(readFileSync(lock, "utf8")).packages ?? {}); }
        catch { lockCache.set(lock, {}); }
      }
      const v = lockCache.get(lock)[`node_modules/${dep}`]?.version;
      if (v) return v;
    }
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return null;
}

const out = [];
out.push("# Generated by build-baseline.mjs — mechanical layer of repo-intelligence.");
out.push(`# Root: ${ROOT}`);
out.push("components:");
for (const m of manifests.sort()) {
  const rel = relative(ROOT, m);
  if (m.endsWith("package.json")) {
    let pkg;
    try { pkg = JSON.parse(readFileSync(m, "utf8")); } catch { continue; }
    const deps = { ...(pkg.dependencies ?? {}), ...(pkg.devDependencies ?? {}) };
    if (!Object.keys(deps).length) continue;
    out.push(`  - manifest: ${rel}`);
    out.push(`    ecosystem: npm`);
    out.push(`    dependencies:`);
    for (const [name, declared] of Object.entries(deps).sort()) {
      const resolved = resolvedVersion(m, name);
      out.push(`      - { name: "${name}", declared: "${declared}"${resolved ? `, resolved: "${resolved}"` : ""} }`);
    }
  } else if (m.endsWith("Cargo.toml") || m.endsWith("pyproject.toml")) {
    const text = readFileSync(m, "utf8");
    const section = m.endsWith("Cargo.toml") ? /\[dependencies\]\n([\s\S]*?)(?=\n\[|$)/ : /^\[project\][\s\S]*?dependencies\s*=\s*\[([\s\S]*?)\]/m;
    const match = text.match(section);
    if (!match) continue;
    out.push(`  - manifest: ${rel}`);
    out.push(`    ecosystem: ${m.endsWith("Cargo.toml") ? "cargo" : "python"}`);
    out.push(`    raw_dependencies: |`);
    for (const line of match[1].trim().split("\n").slice(0, 100)) out.push(`      ${line.trim()}`);
  } else {
    out.push(`  - manifest: ${rel}`);
    out.push(`    ecosystem: python`);
    out.push(`    raw_dependencies: |`);
    for (const line of readFileSync(m, "utf8").trim().split("\n").slice(0, 100)) {
      if (line.trim() && !line.startsWith("#")) out.push(`      ${line.trim()}`);
    }
  }
}
out.push("");
out.push("# Fill in manually (LLM layer): environments, feature map, critical paths, risk surfaces.");
console.log(out.join("\n"));
